// GET /api/reports/[id]/download
//
// Returns the report's synthesized markdown as a downloadable .md
// file. Lets the user take a portable, LLM-ready copy of the analysis
// they paid for — same content as the web portal, cleanly formatted
// for dropping into Claude, ChatGPT, Notion, or any other markdown
// consumer.
//
// Access control: delegates to getReport(), which already handles the
// three valid read paths — owner (via auth cookie), share-link
// recipient (via middleware-forwarded token header), and anonymous
// visitor to a public-sample row. If getReport returns null the
// endpoint returns 404 the same way the web pages do.
//
// Link rewrites: the synthesized markdown contains absolute-root
// links like `/reports/<id>/organizations/<name>` that resolve inside
// the platform but go dead when the file is read outside. We rewrite
// those to full `https://www.granted.bio/...` URLs so the recipient
// can click through to the live page (which itself is a growth
// touchpoint — reader lands on the product, sees what it does). The
// absolute-URL form is still clean markdown and reads fine to an LLM.
//
// Added 2026-11-04 per the "AI-friendly export" discussion. See the
// corresponding button in src/app/reports/[id]/page.tsx.

import { NextRequest, NextResponse } from 'next/server'
import { getReport } from '@/lib/reports/fetch-report'

export const runtime = 'nodejs'
export const dynamic = 'force-dynamic'

const APP_URL = (process.env.NEXT_PUBLIC_APP_URL || 'https://www.granted.bio').replace(/\/$/, '')

/**
 * Rewrite every markdown link whose href starts with `/` to an
 * absolute URL pointed at the live platform. Covers the common
 * patterns the synthesizer emits (/reports/..., /org/...,
 * /researcher/..., /project/...). Non-leading-slash links (external
 * URLs, in-doc anchors) are left alone.
 */
function rewriteRelativeLinks(markdown: string): string {
  // Match `](/<path>)` and `](/<path> "title")` but NOT `](//...)`
  // (protocol-relative, treated as external).
  return markdown.replace(/\]\((\/(?!\/)[^)\s]+)([^)]*)\)/g, (_, path, suffix) => {
    return `](${APP_URL}${path}${suffix})`
  })
}

/**
 * Slugify a topic string into a filename-safe stem. Lowercases,
 * replaces runs of non-alphanumerics with hyphens, trims leading/
 * trailing hyphens, caps length. Falls back to "analysis" when the
 * topic is empty or produces an empty slug.
 */
function slugifyTopic(topic: string | null): string {
  if (!topic) return 'analysis'
  const slug = topic
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 60)
  return slug || 'analysis'
}

export async function GET(
  _request: NextRequest,
  { params }: { params: Promise<{ id: string }> },
) {
  const { id } = await params
  const report = await getReport(id)
  if (!report) {
    return NextResponse.json({ error: 'Report not found' }, { status: 404 })
  }
  if (!report.markdown_content) {
    return NextResponse.json({ error: 'Analysis has no content yet' }, { status: 404 })
  }

  const liveUrl = `${APP_URL}/reports/${report.id}`
  const exportedDate = new Date().toISOString().slice(0, 10)

  // Preamble block — short, sign-posts the file as a snapshot of the
  // live analysis, points reader at the live link for cross-link
  // drill-down the static export can't provide.
  const preamble = [
    `> **Exported from granted.bio** · Live analysis: ${liveUrl}`,
    `> *This is a portable snapshot. Click through on any link to open the live analysis, follow drill-downs (projects, researchers, patents, trials), or generate your own.*`,
    '',
    '---',
    '',
  ].join('\n')

  // Sign-off — small block at the end noting the source + CTA back to
  // the product. Lightweight; doesn't clutter the AI-consumable body.
  const signoff = [
    '',
    '---',
    '',
    `*Analysis generated by granted.bio. Browse more analyses or generate your own: ${APP_URL}*`,
    '',
  ].join('\n')

  const body = preamble + rewriteRelativeLinks(report.markdown_content) + signoff
  const filename = `${slugifyTopic(report.topic)}-granted-bio-${exportedDate}.md`

  return new NextResponse(body, {
    status: 200,
    headers: {
      'Content-Type': 'text/markdown; charset=utf-8',
      // RFC 5987 encoding for Unicode-safe filename. Also include the
      // plain `filename=` fallback for older clients.
      'Content-Disposition': `attachment; filename="${filename}"; filename*=UTF-8''${encodeURIComponent(filename)}`,
      // Prevent CDN caching — the markdown can change on refresh.
      'Cache-Control': 'no-store, max-age=0',
    },
  })
}
